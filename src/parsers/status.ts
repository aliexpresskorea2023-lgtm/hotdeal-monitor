/**
 * 딜 상태(status) 판정에서 "종료 아님" 신호를 미리 제거한다.
 *
 * 커뮤니티 핫딜 본문에는 품절/종료 키워드가 들어있지만
 * 실제로는 종료 신호가 아닌 표현이 자주 등장한다. 이걸 그대로
 * 두면 진행중 글이 ended로 오분류된다.
 *
 * 제거 대상:
 * 1. 조건부 — "품절시 종료처리하겠습니다"
 *    "품절이 되면 종료하겠다"는 미래 조건이므로, 작성 시점에는
 *    아직 진행중이다.
 * 2. 과거 서술 — "품절만 뜨던 ○○에 재고가 떴습니다"
 *    과거에 품절이었다는 회상 + 지금은 재입고라는 뜻인데,
 *    "품절" 키워드만 매치되면 ended로 오분류된다.
 *
 * 이 함수는 키워드 판정 직전에 호출되며, 매치된 구문을 빈 문자열로
 * 대체한다. 이후 판정(종료/진행 키워드)은 각 파서가 자기 규칙대로
 * 수행한다 — 여기서는 공통으로 합의된 "거짓 종료 신호 제거"만 담당.
 *
 * 세 파서(fmkorea/ppomppu/ruliweb)가 동일한 로직을 공유해
 * 한 곳에서만 수정하면 전부 반영되도록 한다. (2026-08-26)
 */
export function stripFalseEndedSignals(text: string): string {
  let result = text;

  /*
   * 조건부: "(품절|소진|매진) 시 ... 종료".
   * "시"와 "종료" 사이에 부사 1~2개가 끼는 변형까지 커버한다
   * (예: "소진 시 자동 종료됩니다", "매진 시 조기 종료").
   * 트리거가 품절/소진/매진+시로 고정돼 있어, 조건부가 아닌
   * 진짜 종료 신호("종료되었습니다" 등)는 건드리지 않는다.
   */
  result = result.replace(
    /(품절|소진|매진)\s*시\s*(?:\S+\s+){0,2}?종료\S*/g,
    "",
  );

  result = result.replace(
    /(품절|소진|매진)\s*만\s*(뜨|나|표시)\S*/g,
    "",
  );

  return result;
}
