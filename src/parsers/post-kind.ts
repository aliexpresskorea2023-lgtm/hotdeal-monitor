/*
 * 상품 구성(post kind) 분류 — 2026-09-16 (사용자 확정 스펙).
 *
 * 목적: 핫딜 피드에 "단품" 카드와 "묶음·행사" 카드를 구분하는
 * 필터 축(상품 구성)을 제공한다. 단일 상품 홍보가 아닌 글
 * (기획전·모음전·브랜드위크·전단지·N종 택 등 여러 상품/행사가
 * 한 글에 묶인 경우)을 'bundle'로 라벨링한다.
 *
 * 설계 원칙 — 정밀도 우선(보수적):
 * - 오탐(단품을 묶음으로)은 단품 뷰에서 실제 딜을 숨기므로 가장
 *   해롭다. 그래서 강한 신호만 쓰고, 애매한 글은 'single'로 둔다.
 * - 미탐(묶음이 단품으로 남음)은 현행 상태와 같고 어드민 오버라이드
 *   (posts.post_kind_override)로 정정할 수 있어 상대적으로 안전하다.
 * - 세트 상품(선물세트·4종세트 등 1 SKU 복합구성)과 단일 제품군의
 *   변형 나열(예: 독거미 F108 키보드 5종)은 사용자 확정대로 'single'
 *   유지 — 그래서 "세트"는 신호로 쓰지 않고, 딜 수도 신호로 쓰지
 *   않는다(변형 나열 글도 딜이 여러 개다).
 *
 * 주의: 전단지·종합차트·멤버십데이·쇼핑라이브 예고 등은 이미
 * src/db/exclusion.ts가 피드에서 제외한다. 여기 분류는 그 제외를
 * 통과해 실제 딜을 가진 다상품 글(기획전·모음·브랜드위크 등)을
 * 대상으로 하며, 제외 규칙이 완화·복원되어도 일관되게 동작하도록
 * 관련 키워드는 여기에도 defensively 포함한다.
 */

/** 상품 구성 값. 'single' = 단품, 'bundle' = 묶음·행사. */
export type PostKind = "single" | "bundle";

/*
 * 강한 묶음 신호 (정밀도 우선으로 실데이터 대조해 좁힘).
 * 각 패턴은 2026-09-16 로컬 DB(딜 있는 posts 8,787건) 전수 스캔으로
 * 눈검증했다 — 매칭 표본이 거의 전부 실제 다상품/행사 글.
 *
 * 한글은 \w(워드 문자)가 아니라 \b 경계가 "외" 앞에서 성립하지
 * 않으므로, "외"는 (?:^|\s)로 앞 경계를 직접 지정한다.
 */
const BUNDLE_PATTERNS: RegExp[] = [
  /기획전/,                       // 브랜드·카테고리 기획전
  /모음/,                         // 모음집·모음전·특가 모음·할인모음·쿠폰 모음
  /전단(?!계)/,                   // 마트 전단지 ("전단계"=당뇨 전단계 오탐 제외)
  /(브랜드|멤버십|메가|톡딜|쇼핑|가전|네이버|썸머|윈터)\s*위크/, // 브랜드위크·메가위크 등
  /위크\s*(세일|할인|미리|코드)/, // "~위크 세일/할인코드"
  /원데이\s*세일/,                // 오늘의집 원데이세일
  /넾다\s*세일/,                  // 네이버 넾다세일(브랜드 종합 행사)
  /프로모션/,                     // 브랜드 종합 프로모션 (게임번들은 아래에서 제외)
  /\d+\s*종\s*(모음|중\s*택|고르기)/, // "25종 중 택1", "50종 모음"
  /(?:^|\s)외\s*(다수|\d+\s*종|골라|택1|종류)/, // "A 외 다수", "A 외 4종 골라담기"
];

/*
 * 상품명 오탐 하드 제외. BUNDLE_PATTERNS보다 우선한다.
 * 강한 신호가 실제 단품에서 우연히 걸리는 경우만 엄선:
 * - 게임번들: 단일 CPU의 게임 번들 "프로모션"(다상품 아님)
 * - 워치페이스: 단일 디지털 제품군의 디자인 여러 개("외 N종", 무형)
 *
 * 주의: 여기에 일반 제품명(데이터·얼라이브·선물세트 등)을 넣지 않는다.
 * 그 단어들은 현재 BUNDLE_PATTERNS를 유발하지 않아 제외할 이유가 없고,
 * 오히려 "데이터 케이블 외 다수"·"선물세트 3종 모음전" 같은 진짜 묶음을
 * 잘못 single로 누르는 부작용만 낳는다.
 */
const FALSE_POSITIVE = /게임\s*번들|워치페이스/;

export interface PostKindInput {
  /** 게시글 제목 */
  title: string | null;
}

/**
 * 게시글의 상품 구성을 분류한다.
 * 정밀도 우선 — 확신 없는 글은 'single'로 둔다(어드민 오버라이드 가능).
 */
export function classifyPostKind(input: PostKindInput): PostKind {
  const title = (input.title ?? "").trim();

  if (title.length === 0) {
    return "single";
  }

  /* 하드 제외가 묶음 신호보다 우선 — 제품명 오탐 방지. */
  if (FALSE_POSITIVE.test(title)) {
    return "single";
  }

  return BUNDLE_PATTERNS.some((re) => re.test(title)) ? "bundle" : "single";
}

/**
 * 카드(아이템) 노출용 상품 구성 합성.
 * 사용자 확정 규칙: 출처 중 하나라도 single이면 단품,
 * 전부 bundle일 때만 묶음·행사. (병합 카드는 단품 정체성 우선)
 */
export function composeItemKind(sourceKinds: PostKind[]): PostKind {
  if (sourceKinds.length === 0) return "single";
  return sourceKinds.some((k) => k === "single") ? "single" : "bundle";
}
